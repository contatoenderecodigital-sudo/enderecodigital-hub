-- Schema do GROOW OS em Postgres. GERADO por db/converter-groow-pg.cjs.
-- Nao edite a mao: ajuste o conversor e rode de novo.
--
-- Vive no schema "groow" porque o public deste banco ja tem outra tabela leads
-- (a dos tenants do hub), sem nenhuma relacao com esta.

CREATE SCHEMA IF NOT EXISTS groow;
SET search_path TO groow, public;

-- Postgres nao tem ON UPDATE CURRENT_TIMESTAMP: precisa de trigger.
CREATE OR REPLACE FUNCTION groow.toca_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

