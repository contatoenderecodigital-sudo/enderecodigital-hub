-- rota /api/admin/prospeccao/email). Convertida à mão junto com o resto.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS groow."prospeccao_emails" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "nome_empresa" VARCHAR(255) NOT NULL DEFAULT '',
  "email" VARCHAR(255) NOT NULL,
  "assunto" VARCHAR(255) NOT NULL DEFAULT '',
  "campanha" VARCHAR(255) NOT NULL DEFAULT '',
  "status" TEXT NOT NULL DEFAULT 'enviado',
  "erro" VARCHAR(500),
  "resend_id" VARCHAR(80),
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY ("id"),
  CONSTRAINT "ck_prospeccao_emails_status" CHECK ("status" IN ('enviado','erro'))
);
CREATE INDEX IF NOT EXISTS "prospeccao_emails_idx_pe_email"
  ON groow."prospeccao_emails" ("email", "created_at");
